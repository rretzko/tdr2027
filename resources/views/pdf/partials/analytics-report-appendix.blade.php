<h2>Appendix: How to read this report</h2>
<p class="note" style="font-size: 10px;">
    This report looks back at the whole audition cycle so you can plan the next one. Every number was captured at the moment the audition was closed, so the report always says the same thing, even if someone edits a score or a student record afterward.
    None of these numbers is a grade for any person. They describe what happened, so you can decide whether anything should change.
</p>

<h3>1. Registration</h3>
<dl class="appendix">
    <dt>Invited, obligated and registered</dt>
    <dd>
        These are the three steps a teacher takes. <strong>Invited</strong> means the teacher was asked to take part.
        <strong>Obligated</strong> means they agreed to the event's terms. <strong>Registered</strong> means they actually entered students.
        A big drop between two steps tells you where teachers are falling away. For example, many invited but few obligated suggests the invitation or the obligation step needs attention.
    </dd>

    <dt>Eligible, engaged and registered students</dt>
    <dd>
        <strong>Eligible</strong> is every student who could have auditioned, based on the invited teachers' rosters.
        <strong>Engaged</strong> is students a teacher started an application for. <strong>Registered</strong> is students whose registration was completed.
        Registered includes every student who registered, whether or not they were later accepted.
    </dd>

    <dt>Fees: due, paid, outstanding and waived</dt>
    <dd>
        <strong>Due</strong> is what registered students owed after any waivers. <strong>Paid</strong> is what was actually received.
        <strong>Outstanding</strong> is the difference, money still owed at Close. <strong>Waived</strong> is the fees you chose to forgive.
    </dd>

    <dt>When students were registered</dt>
    <dd>
        Each bar is one day, and its height is how many students were registered that day. "Day 0" is the final deadline for teacher changes, so −5 means five days before it.
        The colors show which deadline period each day fell in. Tall bars just before a deadline are normal, because people work to deadlines.
        This chart helps you decide when reminder emails will do the most good.
    </dd>

    <dt>Compared with the previous Version</dt>
    <dd>
        How many schools came back from last time, how many didn't, and how many are new. It also shows how student numbers changed, and how many teachers were new to this event or new to TheDirectorsRoom.com altogether.
        Schools that didn't come back are often worth a personal follow-up.
    </dd>

    <dt>Who uploaded recordings</dt>
    <dd>
        Whether each recording was uploaded by the student, the teacher, or someone else (such as an Event Manager).
        If teachers do most of the uploading, instructions and reminders about recordings should be aimed at teachers.
    </dd>

    <dt>Still pending at Close</dt>
    <dd>
        Students a teacher started but never finished registering. They couldn't be adjudicated.
        When several of these belong to one teacher, a short conversation before next year's deadline may prevent it happening again.
    </dd>
</dl>

<h3>2. Adjudication</h3>
<dl class="appendix">
    <dt>Scorings completed and candidates fully scored</dt>
    <dd>
        A <strong>scoring</strong> is one judge finishing one student's score sheet. With three judges in a room, each student needs three scorings.
        A candidate is <strong>fully scored</strong> once every judge in each of their rooms has finished. Both numbers should reach 100% by Close.
    </dd>

    <dt>Median time per candidate</dt>
    <dd>
        The typical time a judge spent per student, measured between saves while working steadily. "Median" means the middle value: half the judges' scorings took longer and half took less.
        It's used instead of an average so that one long break doesn't distort the figure.
    </dd>

    <dt>Scoring per day</dt>
    <dd>
        How many scorings were saved on each day of the judging window. Bunching at the end means many judges left their work late, which is worth knowing when you set the window length or plan reminders.
    </dd>

    <dt>Scales vs Solo</dt>
    <dd>
        Some students are heard in two rooms, for example scales in one and a solo in another. This checks whether students who ranked high in one room also ranked high in the other.
        The agreement figure, <strong>r</strong>, runs from 0 to 1. Near 1 means the two rooms ranked students in much the same order. Near 0 means there was little connection between the two rankings.
        Some difference is expected, because scales and a solo test different skills. The count of students whose standing differed widely is a list worth a second look, because their result depended heavily on one of the two rounds.
    </dd>

    <dt>How the judges scored</dt>
    <dd>
        Each judge is compared only with the other judges in the same room scoring the same students. That keeps the comparison fair, because every judge in a room heard exactly the same recordings.
        Only complete score sheets are counted.
    </dd>

    <dt>Tolerance and "loose"</dt>
    <dd>
        The <strong>tolerance</strong> is a setting you choose for each room: the largest difference allowed between two judges' totals for the same student before the system flags it for review.
        <strong>Largest gap</strong> is the biggest difference that actually happened, and <strong>outside</strong> is how many students went past the tolerance.
        A tolerance is marked <strong>loose</strong> when it is a quarter or more of the whole possible range of scores. For example, a tolerance of 10 on a scale where a judge's total can only vary by 24 points will almost never be reached, so it isn't really checking anything. A smaller number would make the check meaningful.
    </dd>

    <dt>Agreement between judges</dt>
    <dd>
        For each pair of judges in a room, <strong>r</strong> shows how closely they ranked the students in the same order, from 0 (no connection) to 1 (the same order).
        As a rough guide, above 0.8 is strong agreement and 0.6 to 0.8 is reasonable.
        <strong>Average gap</strong> is how many points apart the two judges' totals typically were for the same student.
    </dd>

    <dt>Lean</dt>
    <dd>
        Whether a judge tended to score a little more generously or a little more strictly than the other judges in the room. It's shown in points per student.
        A <strong>plus</strong> means more generous and a <strong>minus</strong> means stricter, whichever way your event scores (high-is-best or low-is-best).
        Differences of a point or so are normal. Because every student in a room is heard by the same judges, a consistent lean affects everyone in that room equally and doesn't change the order of students.
    </dd>

    <dt>Drift</dt>
    <dd>
        Whether a judge's lean changed between the first third and the last third of their list, taken in the order they actually scored it. For example, a judge who started strict and became more generous shows a plus.
        Larger drift can be a sign of fatigue, or of a judge settling into the rubric. Small drift is normal.
    </dd>

    <dt>Values used, top two and flat</dt>
    <dd>
        These describe how much of the scoring scale a judge used. <strong>Values used</strong> is how many of the possible scores (for example, 1 to 9) the judge ever gave.
        <strong>Top two</strong> is the share of all their scores that fell on their two favorite numbers. A high figure, such as 80%, means the judge mostly gave the same couple of scores, which makes it harder to tell students apart.
        <strong>Flat</strong> is the share of score sheets where the judge gave the same number for every item on the sheet. That can mean the judge formed one overall impression rather than scoring each item separately.
    </dd>

    <dt>Revised</dt>
    <dd>
        Score sheets the judge changed more than 10 minutes after first saving them, usually during a second pass through the list. Reviewing is healthy.
        The report can't show how much the scores changed, only that they were changed.
    </dd>

    <dt>Judge check-ins</dt>
    <dd>
        Short optional questions judges answered at points during their work: how focused they felt, what they listened on, and any problems.
        Answers are only ever shown as totals, never by judge or by room, and the details are hidden entirely when too few judges answered to keep them anonymous.
    </dd>
</dl>

<h3>3. Selection</h3>
<dl class="appendix">
    <dt>Decided, accepted and not accepted</dt>
    <dd>
        <strong>Decided</strong> is every student who received a result. The acceptance rate is the share of them who were accepted into an ensemble.
        <strong>No show</strong> means a student was never scored, and <strong>incomplete</strong> means they were only partly scored.
    </dd>

    <dt>Accepted by Ensemble and last season</dt>
    <dd>
        How many students each ensemble took this year, compared with last season's count where one was recorded. The pie charts show how each ensemble's places were shared among the voice parts.
    </dd>

    <dt>The cut-off line</dt>
    <dd>
        The <strong>line</strong> is the score that decided acceptance for one voice part in one ensemble. Students scoring at or better than the line were accepted.
        When the system didn't store the cut-off score, the line shown is the score of the last student accepted (marked *).
    </dd>

    <dt>Closest miss</dt>
    <dd>
        How many points separated the best student who wasn't accepted from the line. A closest miss of 1 means a student missed by a single point. A large number means there was a clear break in the scores at the line.
    </dd>

    <dt>Near: in / out</dt>
    <dd>
        How many accepted students (in) and not-accepted students (out) scored within about 3% of the line, so very close to it on either side.
        A large number here means the decision at that line was tight, and small differences in judging could have changed who was accepted.
    </dd>

    <dt>Medians in / out</dt>
    <dd>
        The middle score of the accepted students and the middle score of the students who weren't accepted. The further apart these are, the more clearly the line separated the two groups.
    </dd>

    <dt>Score distribution chart</dt>
    <dd>
        One row for each cut-off line. The <span style="color: #2a78d6; font-weight: bold;">blue bar</span> stretches from the lowest to the highest total among accepted students.
        The <span style="color: #eb6834; font-weight: bold;">orange bar</span> does the same for students who weren't accepted. The dark mark is the cut-off.
        A row with no orange bar means everyone in that group was accepted. Orange starting right next to the dark mark means the closest misses were very close.
    </dd>
</dl>
